import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

type OpenApiSchema = {
  type?: string;
  format?: string;
  enum?: Array<string | number | null>;
  nullable?: boolean;
  properties?: Record<string, OpenApiSchema>;
  required?: string[];
  items?: OpenApiSchema;
  additionalProperties?: boolean | OpenApiSchema;
  $ref?: string;
  allOf?: OpenApiSchema[];
};

type OpenApiDocument = {
  components?: {
    schemas?: Record<string, OpenApiSchema>;
  };
};

const ROOT = process.cwd();
const OPENAPI_PATH = resolve(ROOT, 'artifacts/intel-openapi.json');
const OUTPUT_PATH = resolve(ROOT, 'packages/sdk/src/generated-intel-contract.ts');

const SCHEMA_TYPE_EXPORTS: Array<{ schemaName: string; exportName: string }> = [
  {
    schemaName: 'IntelHolderProfilesJobAcceptedResponseDto',
    exportName: 'HolderProfilesJobAcceptedResponse',
  },
  {
    schemaName: 'IntelSimilarityJobAcceptedResponseDto',
    exportName: 'SimilarityJobAcceptedResponse',
  },
];

function main(): void {
  const document = JSON.parse(readFileSync(OPENAPI_PATH, 'utf8')) as OpenApiDocument;
  const schemas = document.components?.schemas ?? {};

  const typeBlocks = SCHEMA_TYPE_EXPORTS.map(({ schemaName, exportName }) => {
    const schema = requireSchema(schemas, schemaName);
    const resolved = resolveSchema(schemas, schema);
    return `export interface ${exportName} ${renderObjectType(schemas, resolved, 0)}\n`;
  });

  const hudFields = collectProperties(schemas, requireSchema(schemas, 'WalletHudDto'));
  const behaviorFields = collectProperties(schemas, requireSchema(schemas, 'IntelWalletBehaviorDto'));

  const output = `// AUTO-GENERATED by scripts/generate-intel-sdk-contract.ts
// Source: artifacts/intel-openapi.json
// Do not edit manually.

${typeBlocks.join('\n')}
export const GENERATED_WALLET_HUD_FIELDS = ${JSON.stringify(hudFields, null, 2)} as const;
export const GENERATED_WALLET_BEHAVIOR_FIELDS = ${JSON.stringify(behaviorFields, null, 2)} as const;
`;

  mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
  writeFileSync(OUTPUT_PATH, output, 'utf8');
  console.log(`Wrote generated SDK contract to ${OUTPUT_PATH}`);
}

function requireSchema(schemas: Record<string, OpenApiSchema>, name: string): OpenApiSchema {
  const schema = schemas[name];
  if (!schema) {
    throw new Error(`Schema ${name} not found in Intel OpenAPI artifact`);
  }
  return schema;
}

function resolveSchema(schemas: Record<string, OpenApiSchema>, schema: OpenApiSchema): OpenApiSchema {
  if (schema.$ref) {
    return resolveSchema(schemas, requireSchema(schemas, refName(schema.$ref)));
  }

  if (schema.allOf && schema.allOf.length > 0) {
    return schema.allOf.reduce<OpenApiSchema>((acc, part) => {
      const resolvedPart = resolveSchema(schemas, part);
      return {
        type: acc.type ?? resolvedPart.type ?? 'object',
        nullable: acc.nullable ?? resolvedPart.nullable,
        properties: {
          ...(acc.properties ?? {}),
          ...(resolvedPart.properties ?? {}),
        },
        required: [...new Set([...(acc.required ?? []), ...(resolvedPart.required ?? [])])],
      };
    }, { type: 'object', properties: {}, required: [] });
  }

  return schema;
}

function collectProperties(schemas: Record<string, OpenApiSchema>, schema: OpenApiSchema): string[] {
  const resolved = resolveSchema(schemas, schema);
  return Object.keys(resolved.properties ?? {}).sort();
}

function renderObjectType(
  schemas: Record<string, OpenApiSchema>,
  schema: OpenApiSchema,
  indentLevel: number,
): string {
  const resolved = resolveSchema(schemas, schema);
  const properties = resolved.properties ?? {};
  const required = new Set(resolved.required ?? []);
  const indent = '  '.repeat(indentLevel);
  const innerIndent = '  '.repeat(indentLevel + 1);

  const lines = Object.entries(properties).map(([name, value]) => {
    const optional = required.has(name) ? '' : '?';
    return `${innerIndent}${renderPropertyName(name)}${optional}: ${renderType(schemas, value, indentLevel + 1)};`;
  });

  if (lines.length === 0) {
    return '{}';
  }

  return `{\n${lines.join('\n')}\n${indent}}`;
}

function renderType(
  schemas: Record<string, OpenApiSchema>,
  schema: OpenApiSchema,
  indentLevel: number,
): string {
  if (schema.$ref || schema.allOf) {
    return renderType(schemas, resolveSchema(schemas, schema), indentLevel);
  }

  if (schema.enum && schema.enum.length > 0) {
    const enumType = schema.enum.map((value) => JSON.stringify(value)).join(' | ');
    return applyNullability(enumType, schema.nullable);
  }

  if (schema.type === 'array') {
    const itemType = schema.items ? renderType(schemas, schema.items, indentLevel) : 'unknown';
    return applyNullability(`${itemType}[]`, schema.nullable);
  }

  if (schema.type === 'object') {
    if (schema.properties && Object.keys(schema.properties).length > 0) {
      return applyNullability(renderObjectType(schemas, schema, indentLevel), schema.nullable);
    }

    if (schema.additionalProperties && schema.additionalProperties !== true) {
      const valueType = renderType(schemas, schema.additionalProperties, indentLevel);
      return applyNullability(`Record<string, ${valueType}>`, schema.nullable);
    }

    return applyNullability('Record<string, unknown>', schema.nullable);
  }

  if (schema.type === 'integer' || schema.type === 'number') {
    return applyNullability('number', schema.nullable);
  }

  if (schema.type === 'boolean') {
    return applyNullability('boolean', schema.nullable);
  }

  if (schema.type === 'string') {
    return applyNullability('string', schema.nullable);
  }

  return applyNullability('unknown', schema.nullable);
}

function applyNullability(baseType: string, nullable?: boolean): string {
  return nullable ? `${baseType} | null` : baseType;
}

function renderPropertyName(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

function refName(ref: string): string {
  const parts = ref.split('/');
  return parts[parts.length - 1] ?? ref;
}

main();
